import { test, expect, type Page } from '@playwright/test'

test.use({ screenshot: 'off', trace: 'off' })
const route = '/simulate/plastic-density-separation'
async function pane(page: Page, name: string) {
  if ((page.viewportSize()?.width ?? 1365) <= 1050) await page.getByRole('navigation', { name: 'Khu vực workbench' }).getByRole('button', { name, exact: true }).click()
}
async function start(page: Page) {
  await page.goto(route)
  await page.getByRole('button', { name: 'Bắt đầu thí nghiệm Phân loại nhựa', exact: true }).click()
  await expect(page).toHaveURL(/attempt=/)
  await pane(page, 'Thao tác')
  await page.getByRole('button', { name: 'Chuẩn bị 6 mẫu polymer', exact: true }).click()
  await page.getByRole('button', { name: 'Nạp mẫu & ghi nhận bước làm ướt', exact: true }).click()
}
const scene = (page: Page) => page.getByTestId('plastic-apparatus')
async function noRunningMotion(page: Page) {
  await expect(scene(page)).toHaveAttribute('data-motion-state', 'idle')
  await expect.poll(() => scene(page).evaluate(element => element.getAnimations({ subtree: true }).filter(animation => animation.playState === 'running').length)).toBe(0)
}

test('skip settles to the saved geometry, actions interrupt immediately and restore never replays', async ({ page }, info) => {
  test.skip(info.project.name === 'mobile', 'Desktop exercises visible motion; mobile covers touch and pane visibility below.')
  await page.setViewportSize({ width: 1365, height: 1000 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await start(page)
  await expect(scene(page)).toHaveAttribute('data-scene', 'tank')
  await expect(scene(page)).toHaveAttribute('data-motion-state', 'playing')
  await expect(page.getByRole('button', { name: 'Ghi nhận tách sơ bộ trong nước', exact: true })).toBeEnabled()
  await expect(scene(page)).toHaveAttribute('data-revision', '2')
  const particle = scene(page).locator('[data-motion-particle]').first()
  await scene(page).evaluate(element => element.getAnimations({ subtree: true }).forEach(animation => { animation.pause(); animation.currentTime = 0 }))
  const firstPose = await particle.evaluate(element => getComputedStyle(element).transform)
  if (process.env['PLASTIC_VISUAL_QA'] === '1') await page.screenshot({ path: info.outputPath('plastic-load-start.png') })
  await scene(page).evaluate(element => element.getAnimations({ subtree: true }).forEach(animation => { animation.currentTime = 1500 }))
  const middlePose = await particle.evaluate(element => getComputedStyle(element).transform)
  expect(middlePose).not.toBe(firstPose)
  if (process.env['PLASTIC_VISUAL_QA'] === '1') await page.screenshot({ path: info.outputPath('plastic-load-middle.png') })
  await scene(page).getByRole('button', { name: 'Xem trạng thái cuối', exact: true }).click()
  await noRunningMotion(page)
  expect(await particle.evaluate(element => getComputedStyle(element).transform)).not.toBe(firstPose)
  if (process.env['PLASTIC_VISUAL_QA'] === '1') await page.screenshot({ path: info.outputPath('plastic-load-final.png') })
  const geometry = await scene(page).locator('[data-polymer][data-location]').evaluateAll(elements => elements.map(element => element.getAttribute('transform')))
  await scene(page).getByRole('button', { name: 'Thông tin mẫu HDPE', exact: true }).click()
  await expect(scene(page).getByRole('region', { name: 'Thông tin mẫu HDPE' })).toContainText('0,953 g/cm³')
  await expect(scene(page)).toHaveAttribute('data-revision', '2')
  await page.reload()
  await noRunningMotion(page)
  await expect(scene(page)).toHaveAttribute('data-revision', '2')
  expect(await scene(page).locator('[data-polymer][data-location]').evaluateAll(elements => elements.map(element => element.getAttribute('transform')))).toEqual(geometry)
})

test('live reduced motion stops displacement without changing separation or weighing', async ({ page }, info) => {
  test.skip(info.project.name === 'mobile', 'Desktop covers live preference changes.')
  await page.setViewportSize({ width: 1365, height: 1000 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await start(page)
  await page.getByRole('button', { name: 'Ghi nhận tách sơ bộ trong nước', exact: true }).click()
  await expect(scene(page)).toHaveAttribute('data-motion-state', 'playing')
  await expect(scene(page).locator('[data-polymer="PP"][data-location="floating"]')).toHaveCount(8)
  await expect(scene(page).locator('[data-polymer="PC"][data-location="sinking"]')).toHaveCount(8)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await noRunningMotion(page)
  await expect(scene(page)).toHaveAttribute('data-revision', '3')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await noRunningMotion(page)
  await page.getByRole('button', { name: 'Ghi nhận ly tâm phân đoạn & Cân mẫu', exact: true }).click()
  await expect(scene(page)).toHaveAttribute('data-scene', 'weigh')
  await expect(scene(page)).toContainText('3,90 kg')
  await expect.poll(() => scene(page).evaluate(element => element.getAnimations({ subtree: true }).length)).toBeGreaterThan(0)
  await scene(page).evaluate(element => element.getAnimations({ subtree: true })[0]?.cancel())
  await noRunningMotion(page)
  await expect(scene(page)).toHaveAttribute('data-revision', '4')
  await page.getByRole('button', { name: 'Nhánh nặng (NaCl)', exact: true }).click()
  await page.getByRole('button', { name: 'Chạy NaCl 11–12% w/v', exact: true }).click()
  await scene(page).getByRole('button', { name: 'Thông tin mẫu PS', exact: true }).click()
  await expect(scene(page).getByRole('region', { name: 'Thông tin mẫu PS' })).toContainText('Chưa ghi nhận')
  await expect(scene(page)).toHaveAttribute('data-revision', '6')
  await page.getByRole('button', { name: 'Ghi nhận ly tâm phân đoạn & Cân mẫu', exact: true }).click()
  await expect(scene(page)).toHaveAttribute('data-revision', '7')
  await expect(scene(page)).toContainText('1,606 kg')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await noRunningMotion(page)
})

test('offscreen scenes settle and reset cannot carry an old cue into a new attempt', async ({ page }, info) => {
  test.skip(info.project.name === 'mobile', 'Desktop covers offscreen cleanup and reset; mobile pane cleanup is covered below.')
  await page.setViewportSize({ width: 1365, height: 1000 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await start(page)
  const oldRun = page.url()
  await expect(scene(page)).toHaveAttribute('data-motion-state', 'playing')
  await page.getByRole('region', { name: 'Sổ thực hành phân loại nhựa', exact: true }).scrollIntoViewIfNeeded()
  await noRunningMotion(page)
  await page.getByRole('button', { name: 'Ghi nhận tách sơ bộ trong nước', exact: true }).click()
  await page.getByRole('button', { name: 'Bắt đầu lượt mới', exact: true }).click()
  await page.getByRole('dialog', { name: 'Bắt đầu lượt mới?', exact: true }).getByRole('button', { name: 'Tạo lượt mới', exact: true }).click()
  await expect(page).not.toHaveURL(oldRun)
  await noRunningMotion(page)
  await expect(scene(page)).toHaveAttribute('data-revision', '0')
  await page.goto(oldRun)
  await noRunningMotion(page)
  await expect(scene(page)).toHaveAttribute('data-revision', '3')
})

