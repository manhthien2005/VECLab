import { test, expect, type Page } from '@playwright/test'

test.use({ screenshot: 'off', trace: 'off' })
const route = '/simulate/plastic-density-separation'
async function pane(page: Page, name: string) {
  const nav = page.getByRole('navigation', { name: 'Khu vực workbench', exact: true })
  if ((page.viewportSize()?.width ?? 1280) <= 1050) {
    await expect(nav).toBeVisible()
    const button = nav.getByRole('button', { name, exact: true })
    await button.click()
    await expect(button).toHaveAttribute('aria-pressed', 'true')
  }
}

test('plastic workbench shares the frame, explains submission and restores the saved run', async ({ page }) => {
  await page.goto(route)
  await expect(page.getByRole('region', { name: 'Bàn phân loại nhựa nguyên sinh', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { level: 1, name: 'Phân loại nhựa nguyên sinh', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Bắt đầu thí nghiệm Phân loại nhựa', exact: true }).click()
  await expect(page).toHaveURL(/attempt=[0-9a-f-]{36}/)
  const run = page.url()
  await page.getByRole('button', { name: 'Mở thao tác: Ly tâm & cân', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Ghi nhận ly tâm phân đoạn & Cân mẫu', exact: true })).toBeDisabled()
  await pane(page, 'Mô phỏng')
  await page.getByRole('button', { name: 'Mở thao tác: Chuẩn bị mẫu', exact: true }).click()
  await page.getByRole('button', { name: 'Nộp bài', exact: true }).click()
  const submission = page.getByRole('dialog', { name: 'Kiểm tra trước khi nộp bài', exact: true })
  await expect(submission).toContainText('Chưa hoàn thành')
  await expect(submission.getByRole('button', { name: 'Hoàn tất lượt thực hành', exact: true })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(submission).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Nộp bài', exact: true })).toBeFocused()
  await pane(page, 'Thao tác')
  await page.getByRole('button', { name: 'Chuẩn bị 6 mẫu polymer', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Nạp mẫu & ghi nhận bước làm ướt', exact: true })).toBeEnabled()
  await page.goto('/lab')
  const rows = page.getByRole('region', { name: 'Phân loại nhựa nguyên sinh', exact: true })
  await rows.getByRole('link', { name: 'Tiếp tục thực hành', exact: true }).first().click()
  await expect(page).toHaveURL(run)
  await pane(page, 'Thao tác')
  await expect(page.getByRole('button', { name: 'Nạp mẫu & ghi nhận bước làm ướt', exact: true })).toBeEnabled()
  await page.goto(run + '&view=notebook')
  await expect(page.getByRole('region', { name: 'Sổ thực hành phân loại nhựa', exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Sổ thực hành phân loại nhựa', exact: true })).toContainText('Chưa ghi nhận')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await pane(page, 'Thao tác')
  if ((page.viewportSize()?.width ?? 1280) <= 1050) {
    await page.getByRole('navigation', { name: 'Khu vực workbench', exact: true }).getByRole('button', { name: 'Dụng cụ', exact: true }).click()
  }
  const inventory = page.getByRole('region', { name: 'Danh mục mẫu và dụng cụ', exact: true })
  await expect(inventory.getByRole('button')).toHaveCount(3)
  await inventory.getByRole('button', { name: 'Tìm hiểu sáu mẫu nhựa', exact: true }).click()
  const equipment = page.getByRole('dialog', { name: 'Mẫu & dụng cụ', exact: true })
  await equipment.getByRole('button', { name: 'HDPE', exact: true }).click()
  await expect(equipment.locator('dl')).toContainText('0,953 g/cm³')
  await expect(equipment.locator('dl')).toContainText('chìm')
  await page.keyboard.press('Escape')
  await expect(equipment).not.toBeVisible()
  await inventory.getByRole('button', { name: 'Tìm hiểu Ly tâm và cân', exact: true }).click()
  await equipment.getByRole('button', { name: 'Cân', exact: true }).click()
  await expect(equipment.getByRole('heading', { name: 'Cân khối lượng phân đoạn', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  const guide = page.getByRole('button', { name: 'Hướng dẫn thao tác', exact: true })
  await guide.click()
  const tour = page.getByRole('dialog', { name: 'Làm quen với workbench', exact: true })
  await expect(tour.getByRole('heading', { name: 'Mục tiêu & lượt thực hành', exact: true })).toBeVisible()
  await tour.getByRole('button', { name: 'Tiếp theo', exact: true }).click()
  await expect(tour).toContainText('Ba mục giới thiệu sáu mẫu nhựa')
  await tour.getByRole('button', { name: 'Tôi đã rõ', exact: true }).click()
  await expect(guide).toBeFocused()
})

test('invalid and unknown plastic attempts never turn into a fresh run', async ({ page }) => {
  for (const suffix of ['?attempt=bad', '?attempt=', '?attempt=x&attempt=y', '?attempt=123e4567-e89b-42d3-a456-426614174000']) {
    await page.goto(route + suffix)
    await expect(page.getByRole('heading', { name: 'Chưa mở được lượt thực hành', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Bắt đầu thí nghiệm Phân loại nhựa', exact: true })).toHaveCount(0)
  }
})

test('full plastic workflow submits, opens a frozen report and preserves the previous run on reset', async ({ page }, info) => {
  test.skip(info.project.name === 'mobile', 'The full protocol is covered on desktop; mobile covers navigation and resume.')
  test.setTimeout(180_000)
  await page.goto(route)
  await page.getByRole('button', { name: 'Bắt đầu thí nghiệm Phân loại nhựa', exact: true }).click()
  await expect(page).toHaveURL(/attempt=/)
  const run = page.url()
  await page.getByRole('button', { name: 'Chuẩn bị 6 mẫu polymer', exact: true }).click()
  await page.getByRole('button', { name: 'Nạp mẫu & ghi nhận bước làm ướt', exact: true }).click()
  await page.getByRole('button', { name: 'Ghi nhận tách sơ bộ trong nước', exact: true }).click()
  await page.getByRole('button', { name: 'Ghi nhận ly tâm phân đoạn & Cân mẫu', exact: true }).click()
  await page.getByRole('button', { name: 'Nhánh nhẹ (Ethanol)', exact: true }).click()
  for (const concentration of ['23', '31']) {
    await page.getByRole('button', { name: 'Chạy ethanol ' + concentration + '% v/v', exact: true }).click()
    await page.getByRole('button', { name: 'Ghi nhận ly tâm phân đoạn & Cân mẫu', exact: true }).click()
  }
  await page.getByRole('button', { name: 'Nhánh nặng (NaCl)', exact: true }).click()
  for (const concentration of ['11–12', '20', '40']) {
    await page.getByRole('button', { name: 'Chạy NaCl ' + concentration + '% w/v', exact: true }).click()
    await page.getByRole('button', { name: 'Ghi nhận ly tâm phân đoạn & Cân mẫu', exact: true }).click()
  }
  await page.getByRole('button', { name: 'Xem tổng kết các phân đoạn thu hồi', exact: true }).click()
  await page.getByRole('button', { name: 'Nộp bài', exact: true }).click()
  await page.getByRole('dialog', { name: 'Kiểm tra trước khi nộp bài', exact: true }).getByRole('button', { name: 'Hoàn tất lượt thực hành', exact: true }).click()
  const report = page.getByRole('dialog', { name: 'Báo cáo phân loại nhựa nguyên sinh', exact: true })
  await expect(report).toBeVisible()
  await expect(report).toContainText('Đã hoàn thành cả hai nhánh')
  await expect(report).toContainText('không phải phép đo mới')
  await expect(report.getByRole('table', { name: 'Các phân đoạn đã ghi nhận', exact: true }).locator('tbody tr')).toHaveCount(6)
  await expect(report.getByRole('row', { name: /^PP / })).toContainText('1,912 kg')
  await expect(report.getByRole('row', { name: /^PC / })).toContainText('1,908 kg')
  await page.keyboard.press('Escape')
  await page.goto(run + '&view=report')
  await expect(report).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Bắt đầu lượt mới', exact: true }).click()
  await page.getByRole('dialog', { name: 'Bắt đầu lượt mới?', exact: true }).getByRole('button', { name: 'Tạo lượt mới', exact: true }).click()
  await expect(page).not.toHaveURL(run)
  await page.goto(run + '&view=report')
  await expect(report).toBeVisible()
  await expect(report.getByRole('row', { name: /^PP / })).toContainText('1,912 kg')
})
